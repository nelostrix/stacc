"""Minimal ROS 2 (ament_cmake) package skeleton generator for RSS builds.

Not a real robot_state_publisher/ros2_control setup — just the standard
`<name>_description` package shape (package.xml, urdf/, launch/,
config/controllers.yaml) that a real ROS 2 workspace expects, pre-filled
with the compiled robot's URDF and joint names so it's a real starting
point rather than an empty folder.
"""

from __future__ import annotations

from pathlib import Path

from stacc.core.robot_base import Robot

_PACKAGE_XML = """<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>{name}_description</name>
  <version>0.1.0</version>
  <description>URDF/launch description for {name}, generated by stacc rss build.</description>
  <maintainer email="dev@example.com">stacc rss</maintainer>
  <license>Apache-2.0</license>

  <buildtool_depend>ament_cmake</buildtool_depend>

  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>joint_state_publisher_gui</exec_depend>
  <exec_depend>xacro</exec_depend>
  <exec_depend>rviz2</exec_depend>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
"""

_CMAKE_LISTS = """cmake_minimum_required(VERSION 3.8)
project({name}_description)

find_package(ament_cmake REQUIRED)

install(DIRECTORY urdf launch config DESTINATION share/${{PROJECT_NAME}})

ament_package()
"""

_LAUNCH_FILE = """from launch import LaunchDescription
from launch_ros.actions import Node
from launch.substitutions import Command
from ament_index_python.packages import get_package_share_directory
import os


def generate_launch_description():
    urdf_path = os.path.join(
        get_package_share_directory("{name}_description"), "urdf", "{name}.urdf"
    )
    return LaunchDescription([
        Node(
            package="robot_state_publisher",
            executable="robot_state_publisher",
            parameters=[{{"robot_description": Command(["cat ", urdf_path])}}],
        ),
        Node(
            package="joint_state_publisher_gui",
            executable="joint_state_publisher_gui",
        ),
        Node(
            package="rviz2",
            executable="rviz2",
        ),
    ])
"""


def _controllers_yaml(robot: Robot) -> str:
    actuated = [j.name for j in robot.joints if j.type != "fixed"]
    joints_block = "\n".join(f"      - {name}" for name in actuated) or "      []"
    return f"""controller_manager:
  ros__parameters:
    update_rate: 1000  # Hz

    joint_state_broadcaster:
      type: joint_state_broadcaster/JointStateBroadcaster

    joint_trajectory_controller:
      type: joint_trajectory_controller/JointTrajectoryController

joint_trajectory_controller:
  ros__parameters:
    joints:
{joints_block}
    command_interfaces:
      - position
    state_interfaces:
      - position
      - velocity
"""


def write_ros2_package(robot: Robot, urdf_xml: str, out_dir: Path) -> Path:
    """Write a `<robot.name>_description` ament package under out_dir.

    Returns the package directory path.
    """
    pkg_dir = out_dir / f"{robot.name}_description"
    (pkg_dir / "urdf").mkdir(parents=True, exist_ok=True)
    (pkg_dir / "launch").mkdir(parents=True, exist_ok=True)
    (pkg_dir / "config").mkdir(parents=True, exist_ok=True)

    (pkg_dir / "package.xml").write_text(_PACKAGE_XML.format(name=robot.name))
    (pkg_dir / "CMakeLists.txt").write_text(_CMAKE_LISTS.format(name=robot.name))
    (pkg_dir / "urdf" / f"{robot.name}.urdf").write_text(urdf_xml)
    (pkg_dir / "launch" / "display.launch.py").write_text(_LAUNCH_FILE.format(name=robot.name))
    (pkg_dir / "config" / "controllers.yaml").write_text(_controllers_yaml(robot))

    return pkg_dir
